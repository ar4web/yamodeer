export interface LanguageContextValue {
  language: SupportedLanguage;
  direction: LayoutDirection;
  setLanguage: (lang: SupportedLanguage) => void;
  toggleLanguage: () => void;
  t: (key: string) => string;
  localize: (item: BilingualText | string) => string;
  formatCurrencySAR: (amount: number) => string;
}

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

const STORAGE_KEY_LANG = "ksa_hrms_language_v2";

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<SupportedLanguage>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY_LANG);
      if (saved === "ar" || saved === "en") return saved;
    } catch {
      // ignore storage errors
    }
    return "en";
  });

  const direction: LayoutDirection = language === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    const root = document.documentElement;
    root.setAttribute("dir", direction);
    root.setAttribute("lang", language);
    document.title = TRANSLATION_DICTIONARY[language]["app.browser_title"];
    try {
      localStorage.setItem(STORAGE_KEY_LANG, language);
    } catch {
      // ignore storage errors
    }
  }, [language, direction]);

  const setLanguage = useCallback((lang: SupportedLanguage) => {
    setLanguageState(lang);
  }, []);

  const toggleLanguage = useCallback(() => {
    setLanguageState((prev) => (prev === "en" ? "ar" : "en"));
  }, []);

  const t = useCallback(
    (key: string): string => {
      return TRANSLATION_DICTIONARY[language][key] ?? TRANSLATION_DICTIONARY.en[key] ?? key;
    },
    [language]
  );

  const localize = useCallback(
    (item: BilingualText | string): string => {
      if (typeof item === "string") return item;
      return language === "ar" ? item.ar : item.en;
    },
    [language]
  );

  const formatCurrencySAR = useCallback(
    (amount: number): string => {
      const formatted = amount.toLocaleString(language === "ar" ? "ar-SA" : "en-US", {
        minimumFractionDigits: 2,
        maximumFractionDigits: 2
      });
      return language === "ar" ? `${formatted} ر.س` : `SAR ${formatted}`;
    },
    [language]
  );

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      direction,
      setLanguage,
      toggleLanguage,
      t,
      localize,
      formatCurrencySAR
    }),
    [language, direction, setLanguage, toggleLanguage, t, localize, formatCurrencySAR]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = (): LanguageContextValue => {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return ctx;
};
